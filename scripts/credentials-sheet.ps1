## Commands worth keeping

``````powershell
# every terraform run must go through this, or empty variables destroy the
# AI key and the SMTP password without failing
.\scripts\tf-apply.ps1 -auto-approve

# republish CI secrets and variables after any apply that moved something
.\scripts\setup-github-actions.ps1

# deploy everything and verify all three tiers
gh workflow run deploy.yml

# reload the warehouse and re-grant the operator
gh workflow run deploy.yml -f seed_warehouse=true

# regenerate this sheet
.\scripts\credentials-sheet.ps1
``````

## Rotation

Secrets live in SSM under ``/$prefix/``. Rotate by exporting the new value and
re-applying; the parameter and every consumer follow.

``````powershell
`$env:TF_VAR_ai_api_key    = 'sk-...'
`$env:TF_VAR_smtp_password = '...'
.\scripts\tf-apply.ps1 -auto-approve
``````
"@

$target = if ([IO.Path]::IsPathRooted($Path)) { $Path } else { Join-Path $Root $Path }
[IO.File]::WriteAllText($target, $md, [Text.UTF8Encoding]::new($false))
Write-Host "`nWrote $target"
Write-Host 'Contains live secrets in plaintext. Gitignored via *.local.md -- keep it that way.'
